alter table public.brief_leagues enable row level security;
alter table public.brief_provider_connections enable row level security;
alter table public.brief_league_members enable row level security;
alter table public.brief_league_teams enable row level security;
alter table public.brief_league_memory enable row level security;
alter table public.brief_publication_articles enable row level security;

