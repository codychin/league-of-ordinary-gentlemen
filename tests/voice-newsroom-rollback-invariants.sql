begin;
set local statement_timeout='15s';
do $test$
declare owner_uuid uuid; r uuid; r2 uuid; t uuid; t2 uuid; op uuid:=gen_random_uuid(); op2 uuid:=gen_random_uuid(); j jsonb; n integer;
begin
select o.user_id into strict owner_uuid from public.brief_platform_owners o join auth.users u on u.id=o.user_id where u.email_confirmed_at is not null;
perform set_config('request.jwt.claims','{}',true);
set local role authenticated;
begin perform public.brief_voice_room('status'); raise exception 'FAIL no auth allowed'; exception when insufficient_privilege then null; end;
perform set_config('request.jwt.claims',jsonb_build_object('sub',gen_random_uuid(),'role','authenticated')::text,true);
begin perform public.brief_voice_room('status'); raise exception 'FAIL nonowner allowed'; exception when insufficient_privilege then null; end;
perform set_config('request.jwt.claims',jsonb_build_object('sub',owner_uuid,'role','authenticated')::text,true);
j:=public.brief_voice_room('status');
assert (j->>'reservedMicroUsd')::bigint=0, 'baseline changed';
r:=(public.brief_voice_room('open')->>'roomId')::uuid;
r2:=(public.brief_voice_room('open')->>'roomId')::uuid;
t:=(public.brief_voice_room('claim',r,null,'marnie','test prompt')->>'turnId')::uuid;
begin perform public.brief_voice_room('claim',r,null,'rika','overlap'); raise exception 'FAIL occupied floor allowed'; exception when serialization_failure then null; end;
perform public.brief_voice_room('stage',r,t,'marnie','unheard test');
j:=public.brief_voice_room('read',r);
assert jsonb_array_length(j->'transcript')=1,'unheard text leaked';
perform public.brief_voice_room('reserve',r,t,null,null,1000000,op);
begin perform public.brief_voice_room('reserve',r,t,null,null,1000000,op); raise exception 'FAIL duplicate reserve'; exception when unique_violation then null; end;
begin perform public.brief_voice_room('start',r2,t,null,null,null,op); raise exception 'FAIL wrong room start'; exception when serialization_failure then null; end;
perform public.brief_voice_room('start',r,t,null,null,null,op);
begin perform public.brief_voice_room('start',r,t,null,null,null,op); raise exception 'FAIL duplicate start'; exception when serialization_failure then null; end;
perform public.brief_voice_room('interrupt',r,t);
j:=public.brief_voice_room('read',r);
assert jsonb_array_length(j->'transcript')=1,'interrupted response leaked';
t2:=(public.brief_voice_room('claim',r,null,'rika',null)->>'turnId')::uuid;
begin perform public.brief_voice_room('interrupt',r,t); raise exception 'FAIL stale interrupt'; exception when serialization_failure then null; end;
begin perform public.brief_voice_room('reserve',r,t,null,null,1000000,gen_random_uuid()); raise exception 'FAIL stale reserve'; exception when serialization_failure then null; end;
perform public.brief_voice_room('reserve',r,t2,null,null,1000000,op2);
perform public.brief_voice_room('interrupt',r,t2);
begin perform public.brief_voice_room('start',r,t2,null,null,null,op2); raise exception 'FAIL stale start'; exception when serialization_failure then null; end;
t2:=(public.brief_voice_room('claim',r,null,'hollis',null)->>'turnId')::uuid;
perform public.brief_voice_room('stage',r,t2,'hollis','heard test');
perform public.brief_voice_room('heard',r,t2);
j:=public.brief_voice_room('read',r);
assert jsonb_array_length(j->'transcript')=2,'heard response not appended';
begin perform public.brief_voice_room('heard',r,t2); raise exception 'FAIL replay heard'; exception when serialization_failure then null; end;
perform public.brief_voice_room('reserve',r,null,null,null,18000000,gen_random_uuid());
begin perform public.brief_voice_room('reserve',r,null,null,null,1,gen_random_uuid()); raise exception 'FAIL cap exceeded'; exception when program_limit_exceeded then null; end;
perform public.brief_voice_room('end',r);
j:=public.brief_voice_room('status');
assert (j->>'reservedMicroUsd')::bigint=20000000,'end refunded budget';
begin perform public.brief_voice_room('read',r); raise exception 'FAIL ended room readable'; exception when invalid_parameter_value then null; end;
reset role;
update brief_voice_private.rooms set expires_at=clock_timestamp()-interval '1 second' where id=r2;
set local role authenticated;
begin perform public.brief_voice_room('read',r2); raise exception 'FAIL expired room readable'; exception when invalid_parameter_value then null; end;
perform public.brief_voice_room('end',r2);
reset role;
assert (select count(*)=0 from brief_voice_private.rooms),'room cleanup failed';
assert (select count(*)=3 from brief_voice_private.operations),'operations erased';
end $test$;
rollback;
select 'PASS: rollback-only authenticated RPC invariants' as outcome,(select count(*) from brief_voice_private.rooms) as retained_rooms,(select count(*) from brief_voice_private.operations) as retained_operations,(select total_micro_usd from brief_voice_private.budget) as retained_budget;
